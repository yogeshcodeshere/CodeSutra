function generateFiles() {
  console.log(`Generating 100 concepts... total: ${concepts.length}`);

  // 1. sample-namaste.csv
  const namasteHeader = "code,display,nativeTerm,definition,category,version,effectiveDate\n";
  const namasteRows = concepts
    .map((c) => {
      const cleanDef = `"${c.definition.replace(/"/g, '""')}"`;
      return `${c.code},${c.display},${c.nativeTerm},${cleanDef},${c.category},2026-demo,2026-01-01`;
    })
    .join("\n");
  fs.writeFileSync(path.resolve("data/sample-namaste.csv"), namasteHeader + namasteRows + "\n", "utf8");
  console.log("Wrote data/sample-namaste.csv");

  // 2. sample-icd11.json
  // Build unique ICD-11 concepts (TM2 + biomedicine comorbidities)
  const icdConceptsMap = new Map();
  for (const c of concepts) {
    if (!icdConceptsMap.has(c.tm2Entity)) {
      icdConceptsMap.set(c.tm2Entity, {
        entityId: c.tm2Entity,
        code: c.tm2Code,
        title: c.tm2Title,
        definition: c.tm2Def,
        chapter: "tm2",
        parentId: "chapter-26",
        uri: `https://id.who.int/icd/entity/${c.tm2Entity}`
      });
    }
  }

  // Include standard biomedicine comorbid concepts
  const biomedicineConcepts = [
    {
      entityId: "icd-diabetes",
      code: "5A10",
      title: "Type 2 diabetes mellitus",
      definition: "Biomedicine diagnosis used as a common comorbidity in Ayush workflows.",
      chapter: "biomedicine",
      parentId: "chapter-05",
      uri: "https://id.who.int/icd/entity/icd-diabetes"
    },
    {
      entityId: "icd-hypertension",
      code: "BA00",
      title: "Essential hypertension",
      definition: "Biomedicine diagnosis used as a common comorbidity in Ayush workflows.",
      chapter: "biomedicine",
      parentId: "chapter-11",
      uri: "https://id.who.int/icd/entity/icd-hypertension"
    },
    {
      entityId: "icd-asthma",
      code: "CA23",
      title: "Asthma",
      definition: "Chronic inflammatory disorder of the airways.",
      chapter: "biomedicine",
      parentId: "chapter-12",
      uri: "https://id.who.int/icd/entity/icd-asthma"
    },
    {
      entityId: "icd-osteoarthritis",
      code: "FA00",
      title: "Osteoarthritis of knee",
      definition: "Degenerative joint disease of the knee.",
      chapter: "biomedicine",
      parentId: "chapter-15",
      uri: "https://id.who.int/icd/entity/icd-osteoarthritis"
    },
    {
      entityId: "icd-gerd",
      code: "DA22",
      title: "Gastro-oesophageal reflux disease",
      definition: "Condition which develops when the reflux of stomach contents causes troublesome symptoms.",
      chapter: "biomedicine",
      parentId: "chapter-13",
      uri: "https://id.who.int/icd/entity/icd-gerd"
    }
  ];

  for (const b of biomedicineConcepts) {
    icdConceptsMap.set(b.entityId, b);
  }

  const icdArray = Array.from(icdConceptsMap.values());
  fs.writeFileSync(path.resolve("data/sample-icd11.json"), JSON.stringify(icdArray, null, 2), "utf8");
  console.log(`Wrote data/sample-icd11.json with ${icdArray.length} concepts`);

  // 3. sample-mappings.csv
  const mappingHeader = "namaste_code,tm2_code,equivalence,notes,confidence,reviewed_by\n";
  const mappingRows = concepts
    .map((c) => {
      const cleanNotes = `"${c.notes.replace(/"/g, '""')}"`;
      return `${c.code},${c.tm2Code},${c.equivalence},${cleanNotes},${c.confidence},demo-reviewer`;
    })
    .join("\n");
  fs.writeFileSync(path.resolve("data/sample-mappings.csv"), mappingHeader + mappingRows + "\n", "utf8");
  console.log(`Wrote data/sample-mappings.csv with ${concepts.length} mappings`);
}

